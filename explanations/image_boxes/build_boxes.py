"""
Find where each Korean word of every notice sits in its image, for the Word glossary's boxes on the image.

For each notice in app/translation-experiment-data/notices.json:
  1. OCR the image with Apple's Vision framework (ocr.swift; macOS only), one box per character.
  2. Match the OCR characters to the notice's `korean` text, character by character (difflib), so small OCR
     differences or different line breaks don't matter. Header text in the image that isn't in `korean`
     (the title, subtitle) is simply left unmatched.
  3. Give each Korean word (whitespace token, same as the app's tokenizer) one box per image line it spans:
     the union of its matched characters' boxes.

Writes app/translation-experiment-data/image-boxes.json. Re-run after changing a notice's text or image, then
run `npm run check-data` in app/ (it checks the words still line up with notices.json).

    python3 build_boxes.py            # all notices
    python3 build_boxes.py --only p3_hotel
"""

from __future__ import annotations

import argparse
import difflib
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATA = HERE.parent.parent / "app" / "translation-experiment-data"
NOTICES = DATA / "notices.json"
OUT = DATA / "image-boxes.json"


def ocr(image: Path) -> dict:
    result = subprocess.run(
        ["swift", str(HERE / "ocr.swift"), str(image)], capture_output=True, text=True, check=False
    )
    if result.returncode != 0:
        sys.exit(f"OCR failed for {image}:\n{result.stderr[-2000:]}")
    return json.loads(result.stdout)


def union(boxes: list[list[float]]) -> list[float]:
    x0 = min(b[0] for b in boxes)
    y0 = min(b[1] for b in boxes)
    x1 = max(b[0] + b[2] for b in boxes)
    y1 = max(b[1] + b[3] for b in boxes)
    return [round(x0, 4), round(y0, 4), round(x1 - x0, 4), round(y1 - y0, 4)]


def boxes_for_notice(korean: str, page: dict) -> tuple[list[dict], float]:
    # Korean side: every non-space character, tagged with its word index.
    tokens = korean.split()
    k_chars: list[str] = []
    k_token: list[int] = []
    for ti, tok in enumerate(tokens):
        for ch in tok:
            k_chars.append(ch)
            k_token.append(ti)

    # Image side: OCR characters in reading order (Vision returns lines top to bottom), tagged with their line.
    lines = sorted(page["lines"], key=lambda l: (round(l["box"][1], 2), l["box"][0]))
    o_chars: list[str] = []
    o_box: list[list[float]] = []
    o_line: list[int] = []
    for li, line in enumerate(lines):
        for c in line["chars"]:
            o_chars.append(c["c"])
            o_box.append(c["box"])
            o_line.append(li)

    matcher = difflib.SequenceMatcher(a=k_chars, b=o_chars, autojunk=False)
    per_token: dict[int, dict[int, list[list[float]]]] = {}
    matched = 0
    for block in matcher.get_matching_blocks():
        for n in range(block.size):
            ki, oi = block.a + n, block.b + n
            per_token.setdefault(k_token[ki], {}).setdefault(o_line[oi], []).append(o_box[oi])
            matched += 1

    words = []
    for ti, tok in enumerate(tokens):
        by_line = per_token.get(ti, {})
        words.append({"text": tok, "boxes": [union(by_line[li]) for li in sorted(by_line)]})
    return words, matched / max(1, len(k_chars))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--only", action="append", help="notice id (repeatable); default all")
    args = ap.parse_args()

    notices = json.loads(NOTICES.read_text(encoding="utf-8"))["documents"]
    out = json.loads(OUT.read_text(encoding="utf-8")) if OUT.exists() else {}
    out["about"] = (
        "Where each Korean word (whitespace token of `korean` in notices.json, in order) appears in the notice "
        "image, for the Word glossary. Boxes are [x, y, width, height] as fractions of the image size, origin "
        "top-left; one per image line the word spans. Generated by explanations/image_boxes/build_boxes.py "
        "(Apple Vision OCR); don't edit by hand."
    )
    out.setdefault("notices", {})

    for n in notices:
        if args.only and n["id"] not in args.only:
            continue
        if not n.get("image"):
            print(f"{n['id']}: no image, skipped")
            continue
        page = ocr(DATA / n["image"])
        words, coverage = boxes_for_notice(n["korean"], page)
        missing = [w["text"] for w in words if not w["boxes"]]
        out["notices"][n["id"]] = {"image": n["image"], "words": words}
        print(
            f"{n['id']}: {len(words)} words, {coverage:.1%} of characters matched"
            + (f"; no box for: {' '.join(missing)}" if missing else "")
        )

    OUT.write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"\nWrote {OUT.relative_to(HERE.parent.parent)}. Now run `npm run check-data` in app/.")


if __name__ == "__main__":
    main()
